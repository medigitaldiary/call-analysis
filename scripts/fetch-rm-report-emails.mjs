/**
 * fetch-rm-report-emails.mjs
 *
 * Fetches BondScanner day-end report emails from Gmail via IMAP (Apr 22 – May 8 2026)
 * and extracts per-RM performance data from the HTML body.
 *
 * Usage:
 *   node scripts/fetch-rm-report-emails.mjs
 *   node scripts/fetch-rm-report-emails.mjs --from 2026-04-22 --to 2026-05-08
 *   node scripts/fetch-rm-report-emails.mjs --json   (output raw JSON)
 */

import { ImapFlow }    from 'imapflow';
import { simpleParser } from 'mailparser';
import { readFileSync }  from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath }    from 'url';

// ── Load env files (.env.local then .env.production.local) ──────────────────
const __dirname = dirname(fileURLToPath(import.meta.url));

function loadEnvFile(filePath) {
  try {
    const text = readFileSync(filePath, 'utf8');
    for (const line of text.split('\n')) {
      const t = line.trim();
      if (!t || t.startsWith('#')) continue;
      const i = t.indexOf('=');
      if (i < 0) continue;
      const k = t.slice(0, i).trim();
      const v = t.slice(i + 1).trim().replace(/^"/, '').replace(/"$/, '');
      if (v) process.env[k] = v; // only set if non-empty (production overrides empty .env.local values)
    }
  } catch { /* file may not exist */ }
}

loadEnvFile(resolve(__dirname, '../.env.local'));
loadEnvFile(resolve(__dirname, '../.env.production.local'));

// ── CLI args ─────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const getArg = (flag) => { const i = args.indexOf(flag); return i >= 0 ? args[i + 1] : null; };
const FROM_DATE  = getArg('--from') ?? '2026-04-22';
const TO_DATE    = getArg('--to')   ?? '2026-05-08';
const JSON_MODE  = args.includes('--json');

// ── HTML parsing helpers ─────────────────────────────────────────────────────

function stripTags(html) {
  return html.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&middot;/g, '·').trim();
}

/**
 * Extract the date shown in the email header: "Day End Report — DD Month YYYY"
 */
function extractReportDate(html) {
  const m = html.match(/Day End Report[^—]*—\s*([^<"]+)/);
  if (m) return m[1].trim();
  // Fallback: pull from "Generated by Radar · BondScanner · DD Month YYYY"
  const m2 = html.match(/Generated by Radar[^·]*·[^·]*·\s*([^<"]+)/);
  return m2 ? m2[1].trim() : null;
}

/**
 * Extract Agent Performance table rows.
 * Columns: Agent | Calls | Follow-ups | Median Score | Best Call
 *
 * HTML pattern (from lib/gmail.ts):
 *   <td style="...font-weight:600;">{agent}</td>
 *   <td style="...color:#3b82f6;font-weight:600;">{calls}</td>
 *   <td style="...">{follow_ups}</td>
 *   <td style="...color:#f59e0b;font-weight:600;">{median}</td>
 *   <td style="...color:#6b7280;font-size:12px;">{best_call}</td>
 */
function extractAgentPerfTable(html) {
  // Find the Agent Performance section
  const sectionMatch = html.match(/Agent Performance<\/h2>([\s\S]*?)<\/table>/);
  if (!sectionMatch) return [];

  const tableHtml = sectionMatch[1];

  // Match each data row (skip header row which has <th> elements)
  const rowRegex = /<tr[^>]*>([\s\S]*?)<\/tr>/g;
  const results = [];
  let m;

  while ((m = rowRegex.exec(tableHtml)) !== null) {
    const rowHtml = m[1];
    if (rowHtml.includes('<th')) continue; // skip header

    const cells = [];
    const cellRegex = /<td[^>]*>([\s\S]*?)<\/td>/g;
    let cm;
    while ((cm = cellRegex.exec(rowHtml)) !== null) {
      cells.push(stripTags(cm[1]).trim());
    }

    if (cells.length >= 4) {
      results.push({
        agent:        cells[0],
        total_calls:  parseInt(cells[1], 10) || 0,
        follow_ups:   parseInt(cells[2], 10) || 0,
        median_score: cells[3],  // e.g. "7.5/10"
        best_call:    cells[4] ?? '',
      });
    }
  }

  return results;
}

/**
 * Extract RM Performance Snapshots section.
 *
 * HTML pattern (from lib/gmail.ts — rmSummaryHtml):
 *   <div style="background:#f8fafc;border:1px solid #e2e8f0;border-radius:8px;padding:14px 16px;margin-bottom:10px;">
 *     <div style="...font-weight:700;...">{rmName} <span style="...">· {sessionDate}</span></div>
 *     <div style="...">{summary}</div>
 *     <div style="...">
 *       Median score: <strong ...>{score}</strong>
 *       &nbsp;·&nbsp; Follow-ups: <strong>{followUps}</strong>
 *       &nbsp;·&nbsp; Total calls: <strong>{totalCalls}</strong>
 *     </div>
 *   </div>
 */
function extractRMSnapshots(html) {
  // Find the RM Performance Snapshots section
  const sectionMatch = html.match(/RM Performance Snapshots<\/h2>([\s\S]*?)(?:<p style="font-size:12px;color:#6b7280|<\/td>)/);
  if (!sectionMatch) return [];

  const section = sectionMatch[1];

  // Split into individual RM cards
  const cardRegex = /<div style="background:#f8fafc;border:1px solid #e2e8f0;border-radius:8px;padding:14px 16px;margin-bottom:10px;">([\s\S]*?)<\/div>\s*<\/div>\s*<\/div>/g;
  const results = [];
  let m;

  while ((m = cardRegex.exec(section)) !== null) {
    const cardHtml = m[0];

    // Extract RM name and session date from first inner div
    const nameMatch = cardHtml.match(/font-weight:700[^>]*>([\s\S]*?)<\/div>/);
    let rmName = '', sessionDate = '';
    if (nameMatch) {
      const nameHtml = nameMatch[1];
      // The span contains "· DD Mon YYYY"
      const spanMatch = nameHtml.match(/<span[^>]*>·\s*([^<]+)<\/span>/);
      sessionDate = spanMatch ? spanMatch[1].trim() : '';
      rmName = stripTags(nameHtml.replace(/<span[^>]*>[\s\S]*?<\/span>/, '')).trim();
    }

    // Extract summary (second inner div)
    const summaryMatch = cardHtml.match(/line-height:1\.6;">([\s\S]*?)<\/div>/);
    const summary = summaryMatch ? stripTags(summaryMatch[1]).trim() : '';

    // Extract metrics from third inner div
    const metricsMatch = cardHtml.match(/Median score:.*?<strong[^>]*>([^<]+)<\/strong>[\s\S]*?Follow-ups:.*?<strong>([^<]+)<\/strong>[\s\S]*?Total calls:.*?<strong>([^<]+)<\/strong>/);
    const medianScore = metricsMatch ? metricsMatch[1].trim() : 'N/A';
    const followUps   = metricsMatch ? parseInt(metricsMatch[2], 10) || 0 : 0;
    const totalCalls  = metricsMatch ? parseInt(metricsMatch[3], 10) || 0 : 0;

    if (rmName) {
      results.push({ rmName, sessionDate, summary, medianScore, followUps, totalCalls });
    }
  }

  return results;
}

/**
 * Extract total calls and talk time from the overview stats bar.
 */
function extractOverview(html) {
  // Stats bar contains total_calls, unique_customers, talk_time, reps_on_duty
  // color:#3b82f6;font-size:24px;font-weight:700;">{total_calls}
  const callsMatch    = html.match(/color:#3b82f6;font-size:24px;font-weight:700;">(\d+)/g);
  const talkTimeMatch = html.match(/color:#f59e0b;font-size:24px;font-weight:700;">([^<]+)</);
  return {
    total_calls: callsMatch ? parseInt(callsMatch[0].replace(/\D/g, ''), 10) : null,
    talk_time:   talkTimeMatch ? talkTimeMatch[1].trim() : null,
  };
}

// ── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  const user = process.env.GMAIL_USER;
  const pass = process.env.GMAIL_APP_PASSWORD;

  if (!user || !pass) {
    console.error('❌  GMAIL_USER and GMAIL_APP_PASSWORD must be set in .env.local');
    process.exit(1);
  }

  console.error(`🔌  Connecting to Gmail IMAP as ${user} …`);

  const client = new ImapFlow({
    host:   'imap.gmail.com',
    port:   993,
    secure: true,
    auth:   { user, pass },
    logger: false,
  });

  await client.connect();
  console.error('✅  Connected\n');

  const allEmailData = [];

  // Search both INBOX and [Gmail]/Sent Mail — day-report emails are sent FROM
  // this account, so they live in Sent, not Inbox.
  const mailboxes = ['INBOX', '[Gmail]/Sent Mail'];

  const subjects = [
    'Call analysis: Day end report',
    '[TEST] Day end report - Call Analysis',
    '[Internal] Call analysis: Day end report',
  ];
  const sinceDate  = new Date(FROM_DATE + 'T00:00:00Z');
  const beforeDate = new Date(TO_DATE   + 'T23:59:59Z');

  const seenMessageIds = new Set();

  for (const mailbox of mailboxes) {
    let lock;
    try {
      lock = await client.getMailboxLock(mailbox);
    } catch {
      console.error(`  ⚠️  Could not open mailbox "${mailbox}" — skipping`);
      continue;
    }

    try {
      console.error(`📂  Searching "${mailbox}" (${FROM_DATE} → ${TO_DATE})…`);

      let allUids = [];
      for (const subject of subjects) {
        const uids = await client.search({
          subject,
          since:  sinceDate,
          before: beforeDate,
        }, { uid: true });
        console.error(`   "${subject}" → ${uids.length} emails`);
        allUids.push(...uids);
      }

      allUids = [...new Set(allUids)].sort((a, b) => a - b);
      console.error(`   Subtotal: ${allUids.length} unique UIDs\n`);

      for (const uid of allUids) {
        const msg = await client.fetchOne(uid.toString(), { source: true }, { uid: true });
        if (!msg) continue;

        const parsed = await simpleParser(msg.source);

        // Deduplicate across mailboxes by Message-ID
        const msgId = parsed.messageId ?? `${mailbox}-${uid}`;
        if (seenMessageIds.has(msgId)) continue;
        seenMessageIds.add(msgId);

        const html    = parsed.html || '';
        const date    = parsed.date ?? null;
        const subject = parsed.subject ?? '';
        const isTest  = subject.includes('[TEST]') || subject.includes('[Internal]');

        const reportDate  = extractReportDate(html);
        const overview    = extractOverview(html);
        const agentPerf   = extractAgentPerfTable(html);
        const rmSnapshots = extractRMSnapshots(html);

        allEmailData.push({
          uid,
          mailbox,
          emailDate:  date ? date.toISOString().slice(0, 10) : null,
          subject,
          isTest,
          reportDate,
          overview,
          agentPerf,
          rmSnapshots,
        });

        console.error(`  ✉️   ${date?.toISOString().slice(0, 10) ?? '???'} · "${subject.slice(0, 55)}" · agents=${agentPerf.length} snaps=${rmSnapshots.length}`);
      }

    } finally {
      lock.release();
    }
  }

  console.error(`\n📬  Total unique emails processed: ${allEmailData.length}\n`);
  await client.logout();

  // ── Aggregate per-RM data (deduplicated by rmName + sessionDate) ────────────

  // Priority order: production > internal > test (so production data wins for same date)
  const emailsByPriority = [
    ...allEmailData.filter(e => !e.isTest && !e.subject.includes('[Internal]')),
    ...allEmailData.filter(e => e.subject.includes('[Internal]')),
    ...allEmailData.filter(e => e.subject.includes('[TEST]')),
  ];

  const rmMap = new Map(); // rmName → { sessions: Map<sessionDate, data>, totalCalls, followUps, scores[] }

  function processEntry(rmName, sessionDate, totalCalls, followUps, medianScore, summary) {
    if (!rmName) return;
    if (!rmMap.has(rmName)) {
      rmMap.set(rmName, { sessionMap: new Map(), totalCalls: 0, followUps: 0, scores: [] });
    }
    const entry = rmMap.get(rmName);
    // Deduplicate: only add if we haven't seen this rmName+sessionDate, or if new data has more calls
    const key = sessionDate;
    if (!entry.sessionMap.has(key) || entry.sessionMap.get(key).totalCalls < totalCalls) {
      if (entry.sessionMap.has(key)) {
        // Undo previous counts
        const prev = entry.sessionMap.get(key);
        entry.totalCalls -= prev.totalCalls;
        entry.followUps  -= prev.followUps;
        entry.scores      = entry.scores.filter(s => s !== prev._score);
      }
      entry.sessionMap.set(key, { totalCalls, followUps, medianScore, summary, _score: null });
      entry.totalCalls += totalCalls;
      entry.followUps  += followUps;
      if (medianScore && medianScore !== 'N/A') {
        const n = parseFloat(medianScore);
        if (!isNaN(n)) {
          entry.sessionMap.get(key)._score = n;
          entry.scores.push(n);
        }
      }
    }
  }

  for (const email of emailsByPriority) {
    const dateLabel = email.reportDate ?? email.emailDate ?? '?';

    if (email.rmSnapshots.length > 0) {
      for (const snap of email.rmSnapshots) {
        processEntry(snap.rmName, snap.sessionDate || dateLabel, snap.totalCalls, snap.followUps, snap.medianScore, snap.summary);
      }
    } else {
      for (const ap of email.agentPerf) {
        processEntry(ap.agent, dateLabel, ap.total_calls, ap.follow_ups, ap.median_score, '');
      }
    }
  }

  // ── Output ────────────────────────────────────────────────────────────────

  // Convert sessionMap to sorted sessions array for output
  for (const [, d] of rmMap) {
    d.sessions = [...d.sessionMap.entries()]
      .map(([date, v]) => ({ date, ...v }))
      .sort((a, b) => a.date.localeCompare(b.date));
    delete d.sessionMap;
  }

  if (JSON_MODE) {
    const out = {
      emailsProcessed: allEmailData.length,
      dateRange: { from: FROM_DATE, to: TO_DATE },
      rmSummary: Object.fromEntries(
        [...rmMap.entries()].map(([name, d]) => [name, {
          totalCalls: d.totalCalls,
          totalFollowUps: d.followUps,
          followUpRate: d.totalCalls > 0 ? `${Math.round(d.followUps / d.totalCalls * 100)}%` : '0%',
          avgMedianScore: d.scores.length > 0 ? (d.scores.reduce((a, b) => a + b, 0) / d.scores.length).toFixed(2) : 'N/A',
          sessions: d.sessions,
        }])
      ),
    };
    console.log(JSON.stringify(out, null, 2));
    return;
  }

  // Pretty-print table
  console.log('\n');
  console.log('═══════════════════════════════════════════════════════════════════════════════');
  console.log(`  RM Performance Report  ·  ${FROM_DATE} → ${TO_DATE}  ·  Email data`);
  console.log('═══════════════════════════════════════════════════════════════════════════════');
  console.log(`  Emails processed: ${allEmailData.length}  ·  Unique RM-session pairs extracted`);
  console.log('');

  if (rmMap.size === 0) {
    console.log('  ⚠️  No RM data extracted. Check that email HTML parsing matched the expected format.');
    console.log('  Tip: run with --json to inspect raw email data.');
    return;
  }

  // Sort by total calls desc
  const sorted = [...rmMap.entries()].sort((a, b) => b[1].totalCalls - a[1].totalCalls);

  const col  = (s, w) => String(s).padEnd(w).slice(0, w);
  const colR = (s, w) => String(s).padStart(w).slice(0, w);

  console.log(
    col('RM Name', 20) + colR('Calls', 8) + colR('Follow-ups', 12) +
    colR('FU Rate', 10) + colR('Avg Score', 12) + colR('Days', 6)
  );
  console.log('─'.repeat(70));

  for (const [name, d] of sorted) {
    const fuRate   = d.totalCalls > 0 ? `${Math.round(d.followUps / d.totalCalls * 100)}%` : '0%';
    const avgScore = d.scores.length > 0 ? (d.scores.reduce((a, b) => a + b, 0) / d.scores.length).toFixed(2) : 'N/A';
    console.log(
      col(name, 20) + colR(d.totalCalls, 8) + colR(d.followUps, 12) +
      colR(fuRate, 10) + colR(avgScore, 12) + colR(d.sessions.length, 6)
    );
  }

  console.log('─'.repeat(70));
  const totCalls   = sorted.reduce((s, [, d]) => s + d.totalCalls, 0);
  const totFU      = sorted.reduce((s, [, d]) => s + d.followUps, 0);
  const allScores  = sorted.flatMap(([, d]) => d.scores);
  const overallAvg = allScores.length > 0 ? (allScores.reduce((a, b) => a + b, 0) / allScores.length).toFixed(2) : 'N/A';
  console.log(
    col('TOTAL', 20) + colR(totCalls, 8) + colR(totFU, 12) +
    colR(totCalls > 0 ? `${Math.round(totFU / totCalls * 100)}%` : '0%', 10) +
    colR(overallAvg, 12) + colR('', 6)
  );

  console.log('\n\n── Per-RM Session Breakdown ─────────────────────────────────────────────────\n');

  for (const [name, d] of sorted) {
    console.log(`  ${name}  (${d.totalCalls} calls · ${d.sessions.length} working days)`);
    for (const s of d.sessions) {
      console.log(`    ${col(s.date, 20)}  calls=${String(s.totalCalls).padStart(3)}  follow-ups=${String(s.followUps).padStart(3)}  score=${s.medianScore}`);
      if (s.summary) console.log(`      → ${s.summary.slice(0, 110)}${s.summary.length > 110 ? '…' : ''}`);
    }
    console.log('');
  }
}

main().catch((err) => {
  console.error('❌  Fatal error:', err.message);
  process.exit(1);
});
